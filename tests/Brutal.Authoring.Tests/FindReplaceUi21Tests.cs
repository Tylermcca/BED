using System.Text.Json;
using Brutal.Authoring.Data;
using Brutal.Authoring.Editor;
using Brutal.Authoring.Editor.ImGui;
using Brutal.ImGuiApi;
using Xunit;

namespace Brutal.Authoring.Tests;

[Collection(ImGuiCollection.Name)]
public sealed class FindReplaceUi21Tests
{
    private sealed class Rig:IDisposable
    {
        private readonly string root=Directory.CreateTempSubdirectory("find-replace-ui21-").FullName;
        public readonly HeadlessHost Host=new(1600,1000){Drawing=false};
        public readonly DataWorkspace Workspace;
        private readonly Dictionary<string,byte[]> original;
        public Rig(bool extra=false)
        {
            var data=Directory.CreateDirectory(Path.Combine(root,"data")).FullName;var schemas=Directory.CreateDirectory(Path.Combine(root,"schemas")).FullName;
            const string schema="""{"type":"object","properties":{"note":{"type":"string"},"items":{"type":"array","items":{"type":"object","properties":{"name":{"type":"string"},"amount":{"type":"number","maximum":5},"enabled":{"type":"boolean"},"nullable":{"type":["null","string"]}},"required":["name","amount"]}}}}""";
            File.WriteAllText(Path.Combine(schemas,"a.schema.json"),schema.Replace("\"maximum\":5","\"maximum\":10",StringComparison.Ordinal));File.WriteAllText(Path.Combine(schemas,"b.schema.json"),schema);File.WriteAllText(Path.Combine(schemas,"locked.schema.json"),schema);
            File.WriteAllText(Path.Combine(data,"a.json"),"""{"note":"old","items":[{"name":"old","amount":1,"enabled":true,"nullable":null},{"name":"old","amount":2,"enabled":false,"nullable":"set"}]}""");
            File.WriteAllText(Path.Combine(data,"b.json"),"""{"items":[{"name":"old","amount":1,"enabled":true,"nullable":null}]}""");
            File.WriteAllText(Path.Combine(data,"locked.json"),"""{"items":[{"name":"old","amount":1,"enabled":true,"nullable":null}]}""");
            if(extra){File.WriteAllText(Path.Combine(data,"broken.json"),"{");File.WriteAllText(Path.Combine(data,"level.json"),new SceneFormat().Write(Scene.Empty));}
            original=Directory.GetFiles(data).ToDictionary(p=>p,File.ReadAllBytes);
            Workspace=new(DataProject.Open(data,schemas,false,name=>name=="locked.json"?"Generated by the fixture.":null));
            if(extra)Assert.True(Workspace.Documents.BindScene("level.json","scene",out var why),why);
            Assert.True(Workspace.Show("a.json"),Workspace.Said);
            EditorWindow<DataDocument>.Configure(ImGui.GetIO());Host.Frames(Workspace.Draw,4);
            Host.Press(Workspace.Draw,ImGuiKey.H,ctrl:true);Host.Frames(Workspace.Draw,3);
            Assert.Contains(Ui.Snapshot().Nodes,n=>n.Role==UiRole.Window&&n.Label=="Find and replace");
            Assert.True(Node(UiRole.TextField,"Find value").Focused);
        }
        public DataFile Entry(string name)=>Workspace.Project.Find(name)!;
        public DocumentSession<DataDocument> Session(string name)=>Entry(name).Session!;
        public UiNode Node(UiRole role,string label)=>Assert.Single(Ui.Snapshot().Nodes,n=>n.Role==role&&n.Label==label);
        public void Act(UiNode node,UiActions action,string? value=null)
        {
            var ticket=Ui.RequestAction(node.Id,action,value);Host.Frames(Workspace.Draw,3);Assert.Equal(UiActionOutcome.Applied,ticket.Outcome);
        }
        public void Values(string find,string replacement)
        {Act(Node(UiRole.TextField,"Find value"),UiActions.SetValue,find);Act(Node(UiRole.TextField,"Replace with"),UiActions.SetValue,replacement);}
        public void Invoke(string label)=>Act(Node(UiRole.Button,label),UiActions.Invoke);
        public void NativeInvoke(string label)
        {
            for(var i=0;!Node(UiRole.Button,label).Focused&&i<24;i++){Host.Press(Workspace.Draw,ImGuiKey.Tab);Host.Frames(Workspace.Draw,2);}
            Assert.True(Node(UiRole.Button,label).Focused,label);
            Host.Press(Workspace.Draw,ImGuiKey.Enter);Host.Frames(Workspace.Draw,3);
        }
        public void Preview(string find="\"old\"",string replacement="\"new\""){Values(find,replacement);Invoke("Preview matches");}
        public UiNode[] Matches()=>Ui.Snapshot().Nodes.Where(n=>n.Role==UiRole.Checkbox&&n.Label.Contains(".json /",StringComparison.Ordinal)).ToArray();
        public void Unchanged()
        {
            Assert.Empty(Workspace.Project.Dirty);
            foreach(var file in Workspace.Project.Files.Where(f=>f.Session is not null))Assert.Empty(file.Session!.Journal);
            Disk();
        }
        public void Disk(string? except=null){foreach(var (path,bytes) in original)if(Path.GetFileName(path)!=except)Assert.Equal(bytes,System.IO.File.ReadAllBytes(path));}
        public string PathOf(string name)=>Session(name).FilePath!;
        public void Dispose(){Workspace.Dispose();Host.Dispose();Assert.StartsWith(System.IO.Path.GetFullPath(System.IO.Path.GetTempPath()),root,StringComparison.OrdinalIgnoreCase);Directory.Delete(root,true);}
    }
    [Fact]
    public void Native_CtrlH_preview_and_chosen_replacement_use_one_undo_per_file_without_saving_or_touching_read_only_matches()
    {
        using var r=new Rig();
        r.Values("\"old\"","\"new\"");r.NativeInvoke("Preview matches");
        Assert.Equal(5,r.Matches().Length);r.Unchanged();
        var locked=Assert.Single(r.Matches(),n=>n.Label.StartsWith("locked.json",StringComparison.Ordinal));
        Assert.False(locked.Enabled);Assert.Contains("Generated",locked.DisabledReason!);
        var skip=Assert.Single(r.Matches(),n=>n.Label.StartsWith("a.json /items/1/name:",StringComparison.Ordinal));
        r.Act(skip,UiActions.Toggle);
        r.NativeInvoke("Replace chosen");
        Assert.Equal("new",r.Session("a.json").Current.At("/items/0/name")!.Value.GetString());
        Assert.Equal("old",r.Session("a.json").Current.At("/items/1/name")!.Value.GetString());
        Assert.Equal("new",r.Session("a.json").Current.At("/note")!.Value.GetString());
        Assert.Equal("new",r.Session("b.json").Current.At("/items/0/name")!.Value.GetString());
        Assert.Equal("old",r.Session("locked.json").Current.At("/items/0/name")!.Value.GetString());
        foreach(var name in new[]{"a.json","b.json"})
        {Assert.Equal(1,r.Session(name).History.UndoCount);Assert.True(r.Session(name).Dirty);Assert.True(r.Session(name).Undo());Assert.False(r.Session(name).Dirty);}
        Assert.Empty(r.Session("locked.json").Journal);r.Disk();
        Assert.False(r.Node(UiRole.Button,"Replace chosen").Enabled);
    }
    [Theory][InlineData("1","3","/items/0/amount","3")][InlineData("true","false","/items/0/enabled","false")][InlineData("null","\"ready\"","/items/0/nullable","\"ready\"")]
    public void Numeric_boolean_and_null_scalar_values_are_checked_and_recorded_once_per_affected_file(string find,string replacement,string at,string expected)
    {
        using var r=new Rig();r.Preview(find,replacement);r.Invoke("Replace chosen");
        foreach(var name in new[]{"a.json","b.json"})
        {Assert.Equal(expected,r.Session(name).Current.At(at)!.Value.GetRawText());Assert.Equal(1,r.Session(name).History.UndoCount);Assert.True(r.Session(name).Undo());Assert.False(r.Session(name).Dirty);}
        r.Disk();
    }
    [Fact]
    public void Schema_failure_is_named_before_any_file_is_changed()
    {
        using var r=new Rig();r.Preview("1","9");r.Invoke("Replace chosen");
        Assert.Contains(Ui.Snapshot().Nodes,n=>n.Role==UiRole.Text&&n.Label.StartsWith("b.json:",StringComparison.Ordinal));
        r.Unchanged();
    }
    [Theory][InlineData(false)][InlineData(true)]
    public void Replacement_keeps_host_admission_and_focused_subtree_refusals(bool focus)
    {
        using var r=new Rig();r.Preview();
        if(focus)Assert.True(r.Workspace.Window!.Editor.FocusOn("/items/1"));
        else r.Workspace.Window!.Editor.EditRefusal=(_,_,_)=>"Adapter hold.";
        r.Invoke("Replace chosen");
        Assert.Contains(Ui.Snapshot().Nodes,n=>n.Role==UiRole.Text&&n.Label.Contains(focus?"outside the place":"Adapter hold",StringComparison.Ordinal));
        r.Unchanged();
    }
    [Fact]
    public void A_changed_draft_invalidates_the_captured_preview_without_editing_any_other_file()
    {
        using var r=new Rig();r.Preview();var session=r.Session("a.json");
        Assert.True(session.Execute(new SetValue("/note",JsonSerializer.SerializeToElement("later"))));var current=session.Current;var count=session.Journal.Count;
        r.Invoke("Replace chosen");Assert.Same(current,session.Current);Assert.Equal(count,session.Journal.Count);Assert.False(r.Session("b.json").Dirty);
        Assert.Contains(Ui.Snapshot().Nodes,n=>n.Role==UiRole.Text&&n.Label.Contains("document changed",StringComparison.Ordinal));r.Disk();
    }
    [Fact]
    public void Outside_file_change_refuses_the_whole_preflight_and_query_edits_disable_old_choices()
    {
        using var r=new Rig();r.Preview();
        System.IO.File.AppendAllText(r.PathOf("b.json")," ");
        r.Invoke("Replace chosen");Assert.Empty(r.Workspace.Project.Dirty);
        Assert.Contains(Ui.Snapshot().Nodes,n=>n.Role==UiRole.Text&&n.Label.Contains("saved file changed outside BED",StringComparison.Ordinal));r.Disk("b.json");
        r.Values("\"different\"","\"new\"");Assert.False(r.Node(UiRole.Button,"Replace chosen").Enabled);Assert.Empty(r.Matches());
    }
    [Theory][InlineData("{")][InlineData("[1]")][InlineData("{}")]
    public void Invalid_or_container_queries_refuse_with_plain_text_and_no_preview(string find)
    {
        using var r=new Rig();r.Preview(find,"\"new\"");
        Assert.Empty(r.Matches());Assert.False(r.Node(UiRole.Button,"Replace chosen").Enabled);
        Assert.Contains(Ui.Snapshot().Nodes,n=>n.Role==UiRole.Text&&n.Label=="Use quoted text, a number, true, false or null.");r.Unchanged();
    }
    [Fact]
    public void Unreadable_and_scene_documents_are_reported_instead_of_silently_counted_and_Escape_closes_the_panel()
    {
        using var r=new Rig(extra:true);r.Preview();
        Assert.Contains(Ui.Snapshot().Nodes,n=>n.Role==UiRole.Text&&n.Label.StartsWith("broken.json:",StringComparison.Ordinal));
        Assert.Contains(Ui.Snapshot().Nodes,n=>n.Role==UiRole.Text&&n.Label=="level.json: scene documents use scene editing.");
        r.Host.Press(r.Workspace.Draw,ImGuiKey.Escape);r.Host.Frames(r.Workspace.Draw,3);
        Assert.DoesNotContain(Ui.Snapshot().Nodes,n=>n.Role==UiRole.Window&&n.Label=="Find and replace");r.Unchanged();
    }
}
