"""Reproduce SceneStarter's two self-authored OBJ assets and their stable sidecars.

Only these four named outputs are written. Run --check to compare without writes.
No importer, application, subprocess, network or external data is used.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ASSETS = ROOT / "assets"
ASSET_IDS = {"cube": "c0bec0bec0bec0bec0bec0bec0bec0be", "pillar": "a11aa11aa11aa11aa11aa11aa11aa11a"}

def box(name: str, width: float, height: float, depth: float) -> bytes:
    vertices = [(-width/2, 0, -depth/2), (width/2, 0, -depth/2),
                (width/2, height, -depth/2), (-width/2, height, -depth/2),
                (-width/2, 0, depth/2), (width/2, 0, depth/2),
                (width/2, height, depth/2), (-width/2, height, depth/2)]
    triangles = [(1,3,2),(1,4,3),(5,6,7),(5,7,8),(1,5,8),(1,8,4),
                 (2,3,7),(2,7,6),(1,2,6),(1,6,5),(4,8,7),(4,7,3)]
    lines = ["# Self-authored BED sample; generated by generate_assets.py", "o " + name]
    lines += ["v " + " ".join(format(value, ".9g") for value in vertex) for vertex in vertices]
    lines += ["f " + " ".join(map(str, face)) for face in triangles]
    return ("\n".join(lines) + "\n").encode("ascii")

def outputs() -> dict[str, bytes]:
    result: dict[str, bytes] = {}
    for name, size in (("cube", (1, 1, 1)), ("pillar", (.5, 2, .5))):
        source = name + ".obj"
        data = box(name, *size)
        record = {"kind": "asset", "version": 1, "guid": ASSET_IDS[name], "source": source,
                  "sourceHash": hashlib.sha256(data).hexdigest(), "importer": {"id": "obj", "version": 1},
                  "settings": {"scale": 1, "upAxis": "Y"},
                  "provenance": {"author": "BED sample contributors", "licence": "self-authored",
                                 "origin": "samples/SceneStarterProject/generate_assets.py", "declared": "ours"},
                  "aiUse": "allowed"}
        result[source] = data
        result[source + ".asset.json"] = (json.dumps(record, indent=2) + "\n").encode("utf-8")
    return result

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare committed outputs without writing")
    args = parser.parse_args()
    expected = outputs()
    if args.check:
        wrong = [name for name, content in expected.items() if not (ASSETS / name).is_file() or (ASSETS / name).read_bytes() != content]
        if wrong:
            print("Generated sample assets differ: " + ", ".join(wrong))
            return 1
        print("All four generated asset files match.")
        return 0
    ASSETS.mkdir(exist_ok=True)
    for name, content in expected.items():
        (ASSETS / name).write_bytes(content)
    print("Wrote the two self-authored OBJs and their stable sidecars.")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
